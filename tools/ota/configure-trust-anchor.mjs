#!/usr/bin/env node

import { createHash, createPublicKey } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

function usage() {
  console.error(
    "Usage: node configure-trust-anchor.mjs --key <private.pem> " +
      "[--output ../../Core/Inc/firmware_trust_anchor_config.h]",
  );
  process.exit(2);
}

function argument(name, fallback = undefined) {
  const index = process.argv.indexOf(name);
  if (index === -1) {
    return fallback;
  }
  if (index + 1 >= process.argv.length) {
    usage();
  }
  return process.argv[index + 1];
}

function decodeBase64Url(value) {
  const normalized = value.replaceAll("-", "+").replaceAll("_", "/");
  const padding = "=".repeat((4 - (normalized.length % 4)) % 4);
  return Buffer.from(normalized + padding, "base64");
}

function formatBytes(bytes) {
  const lines = [];
  for (let offset = 0; offset < bytes.length; offset += 8) {
    lines.push(
      "    " +
        [...bytes.subarray(offset, offset + 8)]
          .map((value) => `0x${value.toString(16).padStart(2, "0").toUpperCase()}U`)
          .join(", "),
    );
  }
  return lines.join(",\n");
}

const keyArgument = argument("--key");
if (!keyArgument) {
  usage();
}

const outputPath = resolve(
  argument(
    "--output",
    fileURLToPath(
      new URL(
      "../../Core/Inc/firmware_trust_anchor_config.h",
      import.meta.url,
      ),
    ),
  ),
);
const privateKeyPath = resolve(keyArgument);
const privatePem = await readFile(privateKeyPath);
const publicKey = createPublicKey(privatePem);
const jwk = publicKey.export({ format: "jwk" });

if (jwk.kty !== "EC" || jwk.crv !== "P-256" || !jwk.x || !jwk.y) {
  throw new Error("The signing key must be an ECDSA P-256 private key.");
}

const x = decodeBase64Url(jwk.x);
const y = decodeBase64Url(jwk.y);
if (x.length !== 32 || y.length !== 32) {
  throw new Error("Unexpected P-256 public coordinate length.");
}

const rawPublicKey = Buffer.concat([Buffer.from([0x04]), x, y]);
const fingerprint = createHash("sha256").update(rawPublicKey).digest("hex");
const header = `#ifndef INC_FIRMWARE_TRUST_ANCHOR_CONFIG_H_
#define INC_FIRMWARE_TRUST_ANCHOR_CONFIG_H_

#include <stdint.h>

/*
 * Generated by tools/ota/configure-trust-anchor.mjs.
 * Public ECDSA P-256 verification key only. The private signing key must stay
 * outside the repository, build artifacts and device firmware.
 * SHA-256 fingerprint: ${fingerprint}
 */
#define FIRMWARE_TRUST_ANCHOR_CONFIGURED 1U

static const uint8_t firmware_trust_anchor_public_key[65] = {
${formatBytes(rawPublicKey)}
};

#endif /* INC_FIRMWARE_TRUST_ANCHOR_CONFIG_H_ */
`;

await writeFile(outputPath, header, { encoding: "utf8", mode: 0o644 });
console.log(`Public OTA trust anchor written to ${outputPath}`);
console.log(`Public-key SHA-256: ${fingerprint}`);
